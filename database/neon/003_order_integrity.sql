BEGIN;
ALTER TABLE restaurant_tables ADD CONSTRAINT restaurant_tables_id_org_unique UNIQUE(id,organization_id);
ALTER TABLE restaurant_orders DROP CONSTRAINT IF EXISTS restaurant_orders_table_id_fkey;
ALTER TABLE restaurant_orders ADD CONSTRAINT restaurant_orders_table_org_fk
 FOREIGN KEY(table_id,organization_id) REFERENCES restaurant_tables(id,organization_id);
ALTER TABLE restaurant_order_items ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE restaurant_order_items ADD COLUMN IF NOT EXISTS item_status text NOT NULL DEFAULT 'pending'
 CHECK(item_status IN ('pending','preparing','ready','delivered','cancelled'));
ALTER TABLE restaurant_order_items ADD COLUMN IF NOT EXISTS price_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE restaurant_orders ADD COLUMN IF NOT EXISTS order_number bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE restaurant_orders ADD COLUMN IF NOT EXISTS submitted_at timestamptz;
ALTER TABLE restaurant_orders ADD COLUMN IF NOT EXISTS closed_at timestamptz;
ALTER TABLE kitchen_print_jobs ADD COLUMN IF NOT EXISTS claimed_by text;
ALTER TABLE kitchen_print_jobs ADD COLUMN IF NOT EXISTS claim_expires_at timestamptz;
ALTER TABLE kitchen_print_jobs ADD COLUMN IF NOT EXISTS max_attempts integer NOT NULL DEFAULT 5 CHECK(max_attempts > 0);
CREATE INDEX IF NOT EXISTS idx_print_claims ON kitchen_print_jobs(destination_id,status,next_attempt_at,claim_expires_at);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON restaurant_order_items(organization_id,order_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_print_idempotent_destination ON kitchen_print_jobs(organization_id,event_key,destination_id) WHERE destination_id IS NOT NULL;
COMMIT;
