import {test} from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';
import {migrate} from '../scripts/migrations.mjs';
test('printing: batch snapshots, later rounds, reprint idempotency, failure history and tenant isolation',async()=>{
 const db=new PGlite();
 const one=async(q,args=[]) => (await db.query(q,args)).rows[0];
 try{
  await migrate(db,{bootstrap:true,log:()=>{}});
  await db.query(`INSERT INTO "user"(id,name,email) VALUES('print-owner','Print owner','print-owner@example.test'),('print-kitchen','Print kitchen','print-kitchen@example.test'),('print-other','Print other','print-other@example.test')`);
  const org=(await one("SELECT onboard_establishment('print-owner','Print restaurant','print-restaurant') AS id")).id;
  const other=(await one("SELECT onboard_establishment('print-other','Other restaurant','print-other') AS id")).id;
  await db.query("INSERT INTO organization_members(organization_id,user_id,role) VALUES($1,'print-kitchen','kitchen')",[org]);
  const product=(await one("INSERT INTO restaurant_menu_items(organization_id,name,price_cents) VALUES($1,'Pizza',4000) RETURNING id",[org])).id;
  const addon=(await one("INSERT INTO restaurant_addons(organization_id,menu_item_id,name,price_cents) VALUES($1,$2,'Manjericão',100) RETURNING id",[org,product])).id;
  const request=randomUUID(),lines=[{menuItemId:product,quantity:2,addons:[addon],notes:'Sem queijo'}];
  const payload=JSON.stringify({channel:'balcao',notes:'Mesa ao lado da janela',items:lines});
  const digital=(await one("SELECT restaurant_checkout_once($1,'print-owner',$2,$3) AS id",[org,request,payload])).id;
  assert.equal((await one('SELECT count(*)::int AS n FROM restaurant_print_jobs WHERE organization_id=$1',[org])).n,0,'digital mode never silently queues printer jobs');
  const manual=(await one("SELECT restaurant_print_manual($1,'print-owner',$2,$3,$4) AS id",[org,digital,request,randomUUID()])).id;
  assert.ok(manual,'digital mode still offers explicit manual printing');
  await db.query("INSERT INTO restaurant_print_settings(organization_id,mode,printer_name) VALUES($1,'hybrid','Cozinha térmica')",[org]);
  const batch=randomUUID();
  const order=(await one("SELECT restaurant_checkout_once($1,'print-owner',$2,$3) AS id",[org,batch,payload])).id;
  await db.query("SELECT restaurant_checkout_once($1,'print-owner',$2,$3)",[org,batch,payload]);
  const first=await one('SELECT * FROM restaurant_print_jobs WHERE organization_id=$1 AND order_id=$2',[org,order]);
  assert.equal((await one('SELECT count(*)::int AS n FROM restaurant_print_jobs WHERE order_id=$1',[order])).n,1);
  assert.equal(first.snapshot.items[0].quantity,2);
  assert.deepEqual(first.snapshot.items[0].addons,['Manjericão'],'deferred print trigger captures addon inserted after item');
  assert.equal(first.snapshot.items[0].notes,'Sem queijo');
  assert.equal(first.snapshot.new_items,false);
  const later=randomUUID();
  await db.query("SELECT restaurant_add_items_once($1,'print-owner',$2,$3,$4)",[org,order,later,JSON.stringify([{menuItemId:product,quantity:1,addons:[],notes:'Segunda rodada'}])]);
  const second=await one('SELECT * FROM restaurant_print_jobs WHERE order_id=$1 AND batch_id=$2',[order,later]);
  assert.equal(second.snapshot.items.length,1);
  assert.equal(second.snapshot.items[0].quantity,1);
  assert.equal(second.snapshot.new_items,true);
  assert.equal((await one('SELECT snapshot FROM restaurant_print_jobs WHERE id=$1',[first.id])).snapshot.items[0].quantity,2);
  const attempt=randomUUID();
  const firstAttempt=await one("SELECT restaurant_print_record($1,'print-kitchen',$2,$3,'dialog_opened','') AS id",[org,first.id,attempt]);
  assert.deepEqual(await one("SELECT restaurant_print_record($1,'print-kitchen',$2,$3,'dialog_opened','') AS id",[org,first.id,attempt]),firstAttempt);
  await assert.rejects(db.query("SELECT restaurant_print_record($1,'print-owner',$2,$3,'dialog_opened','')",[org,first.id,randomUUID()]),/use_reprint/,'second device cannot silently claim same print twice');
  await db.query("SELECT restaurant_print_record($1,'print-kitchen',$2,$3,'failed','Impressora sem papel')",[org,first.id,randomUUID()]);
  assert.equal((await one('SELECT status FROM restaurant_orders WHERE id=$1',[order])).status,'recebido','physical printer failure cannot cancel or hide kitchen order');
  assert.equal((await one('SELECT count(*)::int AS n FROM restaurant_print_attempts WHERE job_id=$1',[first.id])).n,2);
  const reprintRequest=randomUUID();
  const copy=(await one("SELECT restaurant_print_reissue($1,'print-kitchen',$2,$3) AS id",[org,first.id,reprintRequest])).id;
  assert.equal((await one("SELECT restaurant_print_reissue($1,'print-kitchen',$2,$3) AS id",[org,first.id,reprintRequest])).id,copy);
  assert.deepEqual((await one('SELECT snapshot FROM restaurant_print_jobs WHERE id=$1',[copy])).snapshot,first.snapshot);
  await assert.rejects(db.query("SELECT restaurant_print_record($1,'print-kitchen',$2,$3,'confirmed','')",[org,copy,randomUUID()]),/print_dialog_required/);
  await assert.rejects(db.query("SELECT restaurant_print_reissue($1,'print-other',$2,$3)",[other,first.id,randomUUID()]),/print_job_missing/);
  await assert.rejects(db.query("SELECT restaurant_print_reissue($1,'print-other',$2,$3)",[org,first.id,randomUUID()]),/forbidden/);
 }finally{await db.close();}
});
