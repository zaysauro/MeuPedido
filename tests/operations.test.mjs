import { test } from 'node:test';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';
import { migrate } from '../scripts/migrations.mjs';
test('migrações e operação real PostgreSQL: isolamento, estoque, caixa e delivery',async()=>{
 const remote=process.env.INTEGRATION_DATABASE_URL;
 const {default:pg}=await import('pg');
 const client=remote?new pg.Client({connectionString:remote}):null;
 if(client)await client.connect();
 const db=client?{query:(...a)=>client.query(...a),exec:s=>client.query(s),close:()=>client.end()}:new PGlite();
 try{
 await migrate(db,{bootstrap:true,log:()=>{}});
 await migrate(db,{bootstrap:true,log:()=>{}});
 if(remote) await db.query('BEGIN');
 await db.exec(`INSERT INTO "user"(id,name,email) VALUES('a','Teste A','a@example.test'),('b','Teste B','b@example.test');`);
 const rejects=async(sql,args,pattern)=>{if(remote)await db.query('SAVEPOINT expected_failure');try{await assert.rejects(db.query(sql,args),pattern);}finally{if(remote)await db.query('ROLLBACK TO SAVEPOINT expected_failure');}};
 const one=async(sql,args=[])=> (await db.query(sql,args)).rows[0];
 const org=async(user)=>{const o=await one("INSERT INTO organizations(name,slug) VALUES($1,$1) RETURNING id",['org-'+user]);await db.query("INSERT INTO organization_members VALUES($1,$2,'owner',now())",[o.id,user]);return o.id;};
 const a=await org('a'),b=await org('b');
 const product=await one("INSERT INTO restaurant_menu_items(organization_id,name,price_cents) VALUES($1,'Burger',2500) RETURNING id",[a]);
 const ingredient=await one("INSERT INTO restaurant_ingredients(organization_id,name,unit,quantity) VALUES($1,'Pão','un',10) RETURNING id",[a]);
 await db.query("SELECT restaurant_set_recipe($1,'a',$2,$3)",[a,product.id,JSON.stringify([{ingredientId:ingredient.id,quantity:1}])]);
 const lines=JSON.stringify([{menuItemId:product.id,quantity:2,notes:'Sem cebola',addons:[]}]);
 await rejects("SELECT restaurant_create_order($1,'b','balcao',NULL,NULL,'',$2)",[a,lines],/forbidden/);
 await rejects("SELECT restaurant_create_order($1,'b','balcao',NULL,NULL,'',$2)",[b,lines],/unavailable_item/);
 const order=(await one("SELECT restaurant_create_order($1,'a','balcao',NULL,NULL,'',$2) AS id",[a,lines])).id;
 await rejects("SELECT restaurant_record_payment($1,'a',$2,'dinheiro',1000)",[a,order],/cash_session_required/);
 const cash=(await one("SELECT restaurant_cash_open($1,'a',10000) AS id",[a])).id;
 await rejects("SELECT restaurant_cash_open($1,'a',0)",[a],/duplicate/);
 await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,'preparando')",[a,order]);
 assert.equal(Number((await one('SELECT quantity FROM restaurant_ingredients WHERE id=$1',[ingredient.id])).quantity),8);
 await rejects("SELECT restaurant_kitchen_transition($1,'a',$2,'preparando')",[a,order],/invalid_transition/);
 await db.query("SELECT restaurant_consume_order_inventory($1,'a',$2)",[a,order]);
 assert.equal(Number((await one('SELECT quantity FROM restaurant_ingredients WHERE id=$1',[ingredient.id])).quantity),8);
 await rejects("SELECT restaurant_add_order_items($1,'a',$2,$3)",[a,order,lines],/editable/);
 await rejects("SELECT restaurant_cancel_order($1,'a',$2)",[a,order],/cannot_be_cancelled/);
 await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,'pronto')",[a,order]);
 await db.query("SELECT restaurant_record_payment($1,'a',$2,'dinheiro',2000)",[a,order]);
 await db.query("SELECT restaurant_record_payment($1,'a',$2,'pix',3000)",[a,order]);
 await rejects("SELECT restaurant_record_payment($1,'a',$2,'pix',1)",[a,order],/exceeds_balance/);
 await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,'entregue')",[a,order]);
 await db.query("SELECT restaurant_cash_close($1,'a',$2,12000)",[a,cash]);
 const {randomUUID}=await import('node:crypto');
 const requestId=randomUUID(),payload=JSON.stringify({channel:'balcao',tableId:null,customerId:null,notes:'',items:JSON.parse(lines)});
 const once=(await one("SELECT restaurant_checkout_once($1,'a',$2,$3) AS id",[a,requestId,payload])).id;
 assert.equal((await one("SELECT restaurant_checkout_once($1,'a',$2,$3) AS id",[a,requestId,payload])).id,once);
 const paymentId=randomUUID();
 await db.query("SELECT restaurant_record_payment_once($1,'a',$2,'pix',1000,$3)",[a,once,paymentId]);
 await db.query("SELECT restaurant_record_payment_once($1,'a',$2,'pix',1000,$3)",[a,once,paymentId]);
 assert.equal(Number((await one('SELECT sum(amount_cents) AS paid FROM restaurant_payments WHERE order_id=$1',[once])).paid),1000);
 await rejects("SELECT restaurant_record_payment_once($1,'a',$2,'pix',2000,$3)",[a,once,paymentId],/request_payload_mismatch/);
 const editable=(await one("SELECT restaurant_create_order($1,'a','balcao',NULL,NULL,'',$2) AS id",[a,lines])).id;
 assert.equal((await one("SELECT restaurant_set_discount($1,'a',$2,500) AS total",[a,editable])).total,4500);
 await rejects("SELECT restaurant_set_discount($1,'b',$2,100)",[a,editable],/forbidden/);
 await rejects("SELECT restaurant_set_discount($1,'a',$2,6000)",[a,editable],/invalid_discount/);
 await db.query("SELECT restaurant_set_discount($1,'a',$2,0)",[a,editable]);
 const item=(await one('SELECT id FROM restaurant_order_items WHERE order_id=$1',[editable])).id;
 await db.query("SELECT restaurant_cancel_item($1,'a',$2)",[a,item]);
 await rejects("SELECT restaurant_transfer_order_item($1,'a',$2,$3)",[a,item,once],/invalid_transfer/);
 assert.equal(Number((await one('SELECT total_cents FROM restaurant_orders WHERE id=$1',[editable])).total_cents),0);
 const table=(await one("INSERT INTO restaurant_tables(organization_id,label) VALUES($1,'Mesa integração') RETURNING id",[a])).id;
 const tableOrder=(await one("SELECT restaurant_create_order($1,'a','mesa',$2,NULL,'',$3) AS id",[a,table,lines])).id;
 await db.query("SELECT restaurant_record_payment($1,'a',$2,'pix',5000)",[a,tableOrder]);
 assert.equal(Number((await one('SELECT count(*) AS count FROM restaurant_open_orders WHERE table_id=$1',[table])).count),1,'pagamento antecipado não libera mesa');
 await rejects("SELECT restaurant_close_order($1,'a',$2)",[a,tableOrder],/fulfillment_pending/);
 for(const status of ['preparando','pronto','entregue'])await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,$3)",[a,tableOrder,status]);
 assert.equal(Number((await one('SELECT count(*) AS count FROM restaurant_open_orders WHERE table_id=$1',[table])).count),0,'mesa liberada após pagamento e entrega');
 await db.query("SELECT restaurant_close_order($1,'a',$2)",[a,tableOrder]);
 await db.query("SELECT restaurant_close_order($1,'a',$2)",[a,tableOrder]);
 const customer=(await one("INSERT INTO restaurant_customers(organization_id,name) VALUES($1,'Cliente teste') RETURNING id",[a])).id;
 const address=(await one("INSERT INTO restaurant_customer_addresses(organization_id,customer_id,street,number,neighborhood,city,state,postal_code) VALUES($1,$2,'Rua teste','1','Centro','Curitiba','PR','80000000') RETURNING id",[a,customer])).id;
 const delivery=(await one("SELECT restaurant_create_delivery_order($1,'a',$2,$3,500,'',$4) AS id",[a,customer,address,lines])).id;
 assert.equal((await one('SELECT total_cents FROM restaurant_orders WHERE id=$1',[delivery])).total_cents,5500);
 await rejects("SELECT restaurant_update_delivery($1,'a',$2,'despachado','José','41999999999')",[a,delivery],/invalid_delivery_transition/);
 await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,'preparando')",[a,delivery]);
 await db.query("SELECT restaurant_kitchen_transition($1,'a',$2,'pronto')",[a,delivery]);
 for(const status of ['despachado','em_rota','falhou','despachado','em_rota','entregue'])await db.query("SELECT restaurant_update_delivery($1,'a',$2,$3,$4,$5)",[a,delivery,status,status==='despachado'?'José':null,status==='despachado'?'41999999999':null]);
 assert.equal((await one('SELECT status FROM restaurant_orders WHERE id=$1',[delivery])).status,'entregue','delivery conclui pedido');
 assert.equal((await one('SELECT driver_name FROM restaurant_delivery_tracking WHERE order_id=$1',[delivery])).driver_name,'José');
 await rejects("SELECT restaurant_adjust_ingredient($1,'a',$2,'ajuste_negativo',100,'')",[a,ingredient.id],/insufficient_stock/);
 await rejects("SELECT restaurant_adjust_ingredient($1,'b',$2,'entrada',1,'')",[a,ingredient.id],/forbidden/);
 }finally{if(remote)await db.query('ROLLBACK');await db.close();}
});
